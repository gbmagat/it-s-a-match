"""Turn the research paper's Appendix Table 1 (Flow of Conversation) into
src/content/script.json, copying every message exactly as written.

Run from the project root:  python -I tools/build_script.py
After this, the JSON file can also be edited by hand.

Table layout: numbered rows (1-8) are the match's turns, one cell per
language x style (English F/I/C, then Filipino F/I/C); an unlabeled 6-cell row
after a turn is that turn's next bubble. Lettered rows (A-G) are the
participant's reply choices, one cell per language; unlabeled 2-cell rows
are further choices. Reply G is special: its 4 rows are 2 choices that each
send 2 bubbles (rows 1+3 and rows 2+4), as agreed with the research team.
"""
import json
import os
import sys
import zipfile
from xml.etree import ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCX = os.path.join(ROOT, 'docs', 'research-paper.docx')
OUT = os.path.join(ROOT, 'src', 'content', 'script.json')
W = '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
STYLES = ['formal', 'informal', 'colloquial']


def cell_text(tc):
    parts = []
    for p in tc.iter(W + 'p'):
        parts.append(''.join(t.text or '' for t in p.iter(W + 't')))
    return ' '.join(x for x in parts if x).replace(' ', ' ').strip()


def table_rows():
    with zipfile.ZipFile(DOCX) as z:
        root = ET.fromstring(z.read('word/document.xml'))
    tables = list(root.iter(W + 'tbl'))
    table = tables[-1]  # Table 1 is the last table in the appendix
    for tr in table.findall(W + 'tr'):
        yield [cell_text(tc) for tc in tr.findall(W + 'tc')]


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    turns, replies = [], []
    current = None  # ('turn', turn) or ('reply', reply)
    for cells in table_rows():
        label, rest = cells[0], cells[1:]
        if len(rest) == 6 and all(c in STYLES or c.lower().strip() in STYLES for c in rest):
            continue  # style header row
        if label.isdigit():
            turn = {'en': {s: [] for s in STYLES}, 'fil': {s: [] for s in STYLES}}
            turns.append(turn)
            current = ('turn', turn)
        elif label.isalpha():
            reply = {'id': label, 'rows': []}
            replies.append(reply)
            current = ('reply', reply)
        elif label:
            continue
        if current is None:
            continue  # title rows before the first turn
        kind, item = current
        if kind == 'turn' and len(rest) == 6:
            for i, s in enumerate(STYLES):
                item['en'][s].append(rest[i])
                item['fil'][s].append(rest[3 + i])
        elif kind == 'reply' and len(rest) == 2:
            item['rows'].append({'en': rest[0], 'fil': rest[1]})

    out_replies = []
    for r in replies:
        rows = r['rows']
        if r['id'] == 'G':
            groups = [[rows[0], rows[2]], [rows[1], rows[3]]]
        else:
            groups = [[row] for row in rows]
        out_replies.append({
            'id': r['id'],
            'en': [[row['en'] for row in g] for g in groups],
            'fil': [[row['fil'] for row in g] for g in groups],
        })

    script = {
        '_source': 'Research paper, Appendix Table 1: Flow of Conversation. Generated by tools/build_script.py.',
        '_shape': 'turns[i][language][style] = the match bubbles for turn i+1; replies[i][language] = choices, each a list of bubbles. The chat goes turn 1, reply A, turn 2, reply B, ... reply G, turn 8.',
        'turns': turns,
        'replies': out_replies,
    }
    assert len(turns) == 8, f'expected 8 match turns, found {len(turns)}'
    assert [r['id'] for r in out_replies] == list('ABCDEFG'), [r['id'] for r in out_replies]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(script, f, ensure_ascii=False, indent=2)
    print('Wrote', OUT)
    for i, t in enumerate(turns):
        print(f'turn {i + 1}: ' + ' | '.join(f'{lang}.{s}={t[lang][s]}' for lang in ('en', 'fil') for s in STYLES))
        if i < len(out_replies):
            r = out_replies[i]
            print(f'  reply {r["id"]}: en={r["en"]}  fil={r["fil"]}')


if __name__ == '__main__':
    main()
